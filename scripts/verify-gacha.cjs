const assert = require('node:assert/strict');
const { harness } = require('./verify-media.cjs');
const h = harness();
const profile = () => JSON.parse(h.run('JSON.stringify(gachaState)'));
const pull = n => JSON.parse(h.run(`JSON.stringify(drawCards(${n}))`));
assert.equal(profile().tickets, 10);
assert.equal(h.elements.get('gacha-gallery').children.length, 12);
h.run("startGame('intro1'); openGacha(); Math.random = () => .99;");
assert(!h.elements.get('gacha-panel').classList.contains('hidden'));
const ten = pull(10);
assert.equal(ten.length, 10);
assert.equal(ten.filter(card => card.rarity === 'SR').length, 1, '10th miss must guarantee at least SR');
assert.equal(profile().tickets, 0);
assert.equal(profile().pitySR, 0);
assert.equal(profile().pitySSR, 10);
assert.equal(Object.keys(profile().collection).length, 2);
assert.equal(profile().dust, 8, 'Duplicate R cards should produce one dust each');
const beforeInvalid = JSON.stringify(profile());
assert.equal(pull(1).length, 0);
assert.equal(pull(-1).length, 0);
assert.equal(pull(100).length, 0);
assert.equal(JSON.stringify(profile()), beforeInvalid, 'Invalid/insufficient pulls must be atomic');
h.run('gachaState.tickets = 30');
pull(10); pull(10);
const lastTen = pull(10);
assert.equal(lastTen[9].rarity, 'SSR', '40th miss must guarantee SSR');
assert.equal(profile().pitySSR, 0);
assert.equal(profile().pitySR, 0);
assert.equal(profile().totalDraws, 40);
h.run('gachaState.tickets = 2; Math.random = () => 0;');
pull(1);
assert.equal(profile().pitySR, 0); assert.equal(profile().pitySSR, 0);
const dustBeforeDuplicate = profile().dust;
const duplicate = pull(1)[0];
assert.equal(duplicate.rarity, 'SSR'); assert(!duplicate.isNew);
assert.equal(profile().dust, dustBeforeDuplicate + 10);
h.run('gachaState.dust = 30;');
h.elements.get('gacha-exchange-card').value = 'su-1';
const drawsBeforeExchange = profile().totalDraws;
assert(h.run('exchangeGachaCard()'));
assert.equal(profile().dust, 0); assert.equal(profile().collection['su-1'], 1);
assert.equal(profile().totalDraws, drawsBeforeExchange, 'Exchange must not consume a draw or alter pity');
assert(!h.run('exchangeGachaCard()'), 'Owned cards must not consume dust again');
const ticketsBeforeRewards = profile().tickets;
h.run("renderNode('chapter1_end'); renderNode('chapter1_end');");
assert.equal(profile().tickets, ticketsBeforeRewards + 3, 'Chapter reward must not repeat on rerender');
assert(h.run("grantGachaTickets('game:1:xu', 1)"));
assert(!h.run("grantGachaTickets('game:1:xu', 1)"));
const saved = profile();
const reopened = harness(h.database, h.storage);
assert.deepEqual(JSON.parse(reopened.run('JSON.stringify(gachaState)')), saved, 'Collection, wallet and pity must persist across launches');
assert(!reopened.run("grantGachaTickets('chapter:1', 3)"), 'Reload must not farm chapter tickets');
reopened.run("startGame('campus_end')");
reopened.elements.get('choices-container').children[0].click();
const newRun = JSON.parse(reopened.run('JSON.stringify(gachaState)'));
assert.equal(newRun.tickets, saved.tickets, 'Restart must not grant starter tickets again');
assert.deepEqual(newRun.collection, saved.collection);
assert.equal(newRun.pitySSR, saved.pitySSR);
assert.equal(newRun.run, saved.run + 1);
assert(reopened.run("grantGachaTickets('chapter:1', 3)"), 'A completed new playthrough may earn tickets again');
reopened.run("renderNode('intro2')");
assert(reopened.elements.get('gacha-panel').classList.contains('hidden'));
const brokenStorage = new Map([['class04-card-album-v1', '{broken']]);
const recovered = harness(undefined, brokenStorage);
assert.equal(recovered.run('gachaState.tickets'), 10, 'Malformed saved data must not crash startup');
console.log('Gacha checks passed: initial wallet, atomic pulls, SR/SSR pity, duplicates, exchange, unique quest rewards, persistence, reload protection and new-run collection retention.');
